-- Autores, livros e o vínculo N:N entre eles.
create table autor (
    id            bigint generated by default as identity primary key,
    nome          varchar(150) not null,
    nacionalidade varchar(80)
);

create table livro (
    id                    bigint generated by default as identity primary key,
    titulo                varchar(200) not null,
    isbn                  varchar(13)  not null,
    ano_publicacao        integer,
    categoria             varchar(20)  not null,
    quantidade_total      integer      not null,
    quantidade_disponivel integer      not null,
    constraint uk_livro_isbn unique (isbn),
    constraint ck_livro_categoria check (categoria in ('COMUM', 'RARO')),
    constraint ck_livro_quantidade_total check (quantidade_total > 0),
    -- Garantia final contra estoque negativo, mesmo se alguma gravação escapar da regra atômica.
    constraint ck_livro_quantidade_disponivel
        check (quantidade_disponivel >= 0 and quantidade_disponivel <= quantidade_total)
);

create table livro_autor (
    livro_id bigint not null references livro (id) on delete cascade,
    autor_id bigint not null references autor (id),
    primary key (livro_id, autor_id)
);

create index ix_livro_autor_autor on livro_autor (autor_id);
