-- Leitores e empréstimos.
create table leitor (
    id    bigint generated by default as identity primary key,
    nome  varchar(150) not null,
    email varchar(254) not null,
    constraint uk_leitor_email unique (email)
);

create table emprestimo (
    id                      bigint generated by default as identity primary key,
    livro_id                bigint        not null references livro (id),
    leitor_id               bigint        not null references leitor (id),
    data_emprestimo         date          not null,
    data_prevista_devolucao date          not null,
    data_devolucao          date,
    multa                   numeric(10, 2)
);

-- Um leitor só pode ter um empréstimo ativo do mesmo livro: barra o empréstimo duplicado
-- em retry ou em requisições simultâneas.
create unique index ux_emprestimo_ativo on emprestimo (leitor_id, livro_id) where data_devolucao is null;

create index ix_emprestimo_livro on emprestimo (livro_id);
